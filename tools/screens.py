#!/usr/bin/env python3
"""Regenerates docs/screens/*.png and the site's web/shots/*.webp from the app's built-in demo mode (app.html?demo=1).
No real accounts, no Python worker needed: only a browser. usage: python tools/screens.py"""
import os, sys, threading, functools
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WEB = os.path.join(ROOT, "web"); OUT = os.path.join(ROOT, "docs", "screens"); SHOTS = os.path.join(WEB, "shots")
PORT = 8791
PAGES = [("home", "home"), ("pages", "pages"), ("flows", "flows"), ("queue", "videos"), ("accounts", "accounts"), ("schedule", "schedule"), ("analytics", "stats"), ("settings", "settings"), ("help", "help")]
SITE = {"home", "pages", "flows", "schedule", "stats"}


class Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *a): pass


def main():
    os.makedirs(OUT, exist_ok=True); os.makedirs(SHOTS, exist_ok=True)
    srv = ThreadingHTTPServer(("127.0.0.1", PORT), functools.partial(Quiet, directory=WEB))
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    from playwright.sync_api import sync_playwright
    from PIL import Image
    errors = []
    with sync_playwright() as p:
        b = p.chromium.launch()
        for dev, vp in (("mobile", {"width": 390, "height": 844}), ("desktop", {"width": 1280, "height": 820})):
            ctx = b.new_context(viewport=vp, device_scale_factor=1)
            pg = ctx.new_page()
            pg.on("pageerror", lambda e: errors.append(str(e))); pg.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
            pg.goto(f"http://127.0.0.1:{PORT}/app.html?demo=1#/home"); pg.wait_for_selector("#app", timeout=20000)
            pg.add_style_tag(content=".demobar{display:none!important}")
            for route, name in PAGES:
                pg.evaluate(f"location.hash='#/{route}'"); pg.wait_for_timeout(1000)
                path = os.path.join(OUT, f"{dev}-{name}.png"); pg.screenshot(path=path)
                if name in SITE:
                    Image.open(path).convert("RGB").save(os.path.join(SHOTS, f"{name}-{'d' if dev == 'desktop' else 'm'}.webp"), "WEBP", quality=82, method=6)
            ctx.close()
        b.close()
    srv.shutdown()
    names = sorted(f for f in os.listdir(OUT) if f.endswith(".png"))
    open(os.path.join(OUT, "INDEX.md"), "w").write("# Screens (auto-generated by tools/screens.py from the built-in demo data)\n\n" + "\n".join(f"- {n}" for n in names) + "\n")
    print("wrote", len(names), "screenshots; page errors:", errors or "none")


if __name__ == "__main__":
    main()
