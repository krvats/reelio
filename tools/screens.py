#!/usr/bin/env python3
"""Regenerates docs/screens/*.png from the demo app (fake services, no real accounts). Run before delivering so any new chat can SEE the UI.
usage: python tools/screens.py"""
import os, re, subprocess, sys, time, signal
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "docs", "screens"); os.makedirs(OUT, exist_ok=True)
PORT = 8791
PAGES = [("home", "home"), ("pages", "pages"), ("flows", "flows"), ("queue", "videos"), ("accounts", "accounts"), ("schedule", "schedule"), ("analytics", "stats"), ("settings", "settings"), ("help", "help")]


def main():
    log = open(os.path.join(OUT, ".demo.log"), "w")
    srv = subprocess.Popen([sys.executable, os.path.join(ROOT, "tools", "ui_demo.py"), str(PORT)], stdout=subprocess.PIPE, stderr=log, text=True, start_new_session=True)
    try:
        url = None
        for line in srv.stdout:
            if line.startswith("READY"): url = line.split()[1]; break
        if not url: sys.exit("demo server did not start")
        from playwright.sync_api import sync_playwright
        with sync_playwright() as p:
            b = p.chromium.launch(executable_path=os.environ.get("CHROMIUM", "/opt/pw-browsers/chromium") if os.path.exists("/opt/pw-browsers/chromium") else None)
            for dev, vp in (("mobile", {"width": 390, "height": 844}), ("desktop", {"width": 1280, "height": 820})):
                ctx = b.new_context(viewport=vp, device_scale_factor=1)
                ctx.add_init_script("localStorage.setItem('reelio.token','\"demo\"');localStorage.setItem('reelio.pass','\"test-pass\"');")
                pg = ctx.new_page()
                pg.goto(url); pg.wait_for_selector("#app", timeout=20000)
                for route, name in PAGES:
                    pg.evaluate(f"location.hash='#/{route}'"); pg.wait_for_timeout(900)
                    pg.screenshot(path=os.path.join(OUT, f"{dev}-{name}.png"), full_page=False)
                ctx.close()
            b.close()
    finally:
        try: os.killpg(srv.pid, signal.SIGTERM)
        except Exception: pass
        log.close()
        try: os.remove(os.path.join(OUT, ".demo.log"))
        except Exception: pass
    names = sorted(f for f in os.listdir(OUT) if f.endswith(".png"))
    open(os.path.join(OUT, "INDEX.md"), "w").write("# Screens (auto-generated by tools/screens.py from fake demo data)\n\n" + "\n".join(f"- {n}" for n in names) + "\n")
    print("wrote", len(names), "screenshots to docs/screens")


if __name__ == "__main__":
    main()
